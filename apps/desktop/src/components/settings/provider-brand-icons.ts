/** The mark a named endpoint preset leads its tile with. */
export function brandGlyphForNamedService(id: string): BrandGlyph | undefined {
  const key = NAMED_SERVICE_BRANDS[id];
  return key ? GLYPHS[key] : undefined;
}

/** The mark a sign-in vendor leads its tile with. */
export function brandGlyphForOAuthVendor(vendorId: string): BrandGlyph | undefined {
  const key = OAUTH_VENDOR_BRANDS[vendorId];
  return key ? GLYPHS[key] : undefined;
}

/**
 * The mark a stored provider row leads with, from the same identifiers the row
 * was created from. A plugin-owned row keeps its letter: the service behind it
 * is the plugin's, so a first-party mark would claim an identity it does not
 * own.
 */
export function brandGlyphForProvider(provider: ProviderPublic): BrandGlyph | undefined {
  if (provider.ownerPluginId) return undefined;
  if (provider.authKind === OAUTH_AUTH_KIND) {
    return brandGlyphForOAuthVendor(provider.vendorKey);
  }
  const preset = matchNamedPreset({
    vendorKey: provider.vendorKey,
    baseUrl: provider.baseUrl,
    apiStyle: provider.apiStyle,
  });
  return preset ? brandGlyphForNamedService(preset.id) : undefined;
}
